"""HUNDUN LAB 拉丁字标骨架。

坐标系：x 0..10 字身宽，y 0（顶线）..12（基线），笔画 2，直角，无弧线。
每个字形直接给多边形轮廓，不再靠描边求并——描边在闭口字母的接缝和斜笔端头
上会留下缺口/溢出，改成显式轮廓后几何完全可控，SVG 和 PNG 也更容易对齐。

两种填充：
  union  —— 若干重叠多边形取并集（H/U/L/N 这种由矩形拼出来的字）
  parity —— 外轮廓 + 内孔，奇偶规则（D/B/A 这种带封闭内腔的字）
"""

GLYPH = {
    'H': ('union', [
        [(0, 0), (2, 0), (2, 12), (0, 12)],
        [(8, 0), (10, 0), (10, 12), (8, 12)],
        [(2, 5), (8, 5), (8, 7), (2, 7)],
    ]),
    'U': ('union', [
        [(0, 0), (2, 0), (2, 12), (0, 12)],
        [(8, 0), (10, 0), (10, 12), (8, 12)],
        [(0, 10), (10, 10), (10, 12), (0, 12)],
    ]),
    'L': ('union', [
        [(0, 0), (2, 0), (2, 12), (0, 12)],
        [(0, 10), (10, 10), (10, 12), (0, 12)],
    ]),
    # 斜笔单列一条带子，宽度受控，保证两个三角内腔都开得出来
    'N': ('union', [
        [(0, 0), (2, 0), (2, 12), (0, 12)],
        [(8, 0), (10, 0), (10, 12), (8, 12)],
        [(2, 0), (3.6, 0), (8, 12), (6.4, 12)],
    ]),
    'D': ('parity', [
        [(0, 0), (8, 0), (10, 2), (10, 10), (8, 12), (0, 12)],
        [(2, 2), (6.4, 2), (8, 4), (8, 8), (6.4, 10), (2, 10)],
    ]),
    'B': ('parity', [
        [(0, 0), (7, 0), (9.4, 2.4), (9.4, 4.2), (7.8, 5.8),
         (9.4, 7.4), (9.4, 9.6), (7, 12), (0, 12)],
        [(2, 2), (6.2, 2), (7.4, 3.2), (7.4, 4.2), (6.2, 5.2), (2, 5.2)],
        [(2, 6.8), (6.4, 6.8), (7.6, 8), (7.6, 8.8), (6.4, 10), (2, 10)],
    ]),
    'A': ('parity', [
        [(0, 12), (3.1, 0), (6.9, 0), (10, 12), (7.5, 12), (6.6, 9.3),
         (3.4, 9.3), (2.5, 12)],
        [(3.9, 2.3), (6.1, 2.3), (6.8, 7.5), (3.2, 7.5)],
    ]),
}

ADV = 12.0      # 字距步进
SPACE = 6.5     # 词间距
BOX = 10.0      # 字身宽
CAP = 12.0      # 字高


def width(text, cap):
    s = cap / CAP
    n = sum(1 for c in text if c != ' ')
    return (n * ADV + text.count(' ') * SPACE - (ADV - BOX)) * s


def draw(cv, text, x, y_top, cap, color):
    s = cap / CAP
    cx = x
    for ch in text:
        if ch == ' ':
            cx += SPACE * s
            continue
        kind, polys = GLYPH[ch]
        moved = [[(cx + px * s, y_top + py * s) for px, py in p] for p in polys]
        if kind == 'union':
            cv.union(color, moved)
        else:
            cv.parity(color, moved)
        cx += ADV * s
